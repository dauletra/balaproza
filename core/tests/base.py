"""Базовый `TestCase` для тестов, которым нужен демо-корпус.

Корпус в базе уже есть: его кладёт `core.tests.runner.SeededTestRunner`
один раз на прогон, сразу после миграций. Этот класс остаётся точкой,
через которую тесты объявляют «мне нужны данные портала» — по нему видно,
кто на корпус опирается, и через него же корпус можно будет заменить,
не трогая девятьсот тестов.

Сеять здесь было первым решением и стоило трёх минут на суиту вместо
двадцати семи секунд: `setUpTestData` выполняется на каждом тест-классе,
а классов двести.
"""

from django.core.cache import cache
from django.test import TestCase as DjangoTestCase

from core.models import User


class TestCase(DjangoTestCase):
    """Общий базовый класс: корпус в базе и **пустой кэш**.

    Кэш чистится перед каждым тестом, потому что справочники (жанры,
    ссылки школы, индекс Cmd+K) кэшируются на пять минут, а бэкенд
    локальный — то есть общий для всего прогона. Без очистки тест, который
    заводит жанр или ссылку, видел бы список, собранный предыдущим, и
    падал бы через раз в зависимости от порядка.

    Здесь же он гарантирует, что бюджеты запросов меряют холодный кэш:
    прогретый показал бы число, которого не увидит первый посетитель.
    """

    def setUp(self):
        super().setUp()
        cache.clear()


def user(username: str):
    """Пользователь корпуса по нику — или `None`, если такого нет.

    Слой данных принимает объект, а не строку, и `None` в нём значит
    «гость». Поэтому `user('ghost')` — законный способ спросить хелпер за
    того, кого не существует: ответом будет пустота, а не падение.
    """
    return User.objects.filter(username=username).first()


def login_as(client, username='aidana'):
    """Ввести тестового клиента под настоящим пользователем корпуса.

    Раньше каждый файл писал свой `_login_as_aidana`, раскладывающий три
    ключа в сессию руками: вход настоящий, и
    сессию собирает `django.contrib.auth`: ключ там один и служебный, а
    подделать его в тесте значит проверять не тот вход, которым пользуются.

    Возвращает пользователя — тестам, которым нужны его работы или ник.
    """
    user = User.objects.get(username=username)
    client.force_login(user)
    return user


def login_as_newcomer(client, username='newcomer', name=''):
    """Ввести клиента под человеком, у которого на портале ещё ничего нет.

    Пустые состояния — «Әлі өтінім жоқ», «Сақталғандар жоқ», профиль без
    единой награды — проверялись под выдуманными никами вроде
    `lonely_reader`: сессия объявляла вошедшим того, кого не существует.
    Настоящему входу такой человек нужен в базе, и это к лучшему — пустой
    экран теперь показывают настоящему пустому аккаунту, а не отсутствию
    записи о нём.

    Пароль нерабочий, как и у сидовых: входа по паролю на портале нет.
    """
    user, created = User.objects.get_or_create(
        username=username, defaults={'pen_name': username, 'name': name})
    if created:
        user.set_unusable_password()
        user.save(update_fields=['password'])
    client.force_login(user)
    return user
