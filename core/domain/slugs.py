"""Транслитерация казахской кириллицы в ASCII-slug (Ф15, Этап 1).

`Story.slug`/`Tag.slug` участвуют в маршрутах `<slug:slug>` — стандартный
Django-конвертер матчит только `[-a-zA-Z0-9_]+` и кириллицу не берёт ни
при каком `allow_unicode` поля. Заголовки произведений и имена тегов —
казахские, значит транслитерация обязательна: без неё адрес не открылся
бы по собственной ссылке.

Таблица не обязана совпадать с тем, что демо-корпус выбрал руками
(`_corpus.py`) — там slug'и литералы, подобранные для читаемости, а не
результат кода. Здесь — механическое правило для настоящего ввода автора.
"""

import re

_CYRILLIC_TO_LATIN = {
    'а': 'a', 'ә': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'ғ': 'g', 'д': 'd',
    'е': 'e', 'ё': 'e', 'ж': 'zh', 'з': 'z', 'и': 'i', 'й': 'i', 'к': 'k',
    'қ': 'q', 'л': 'l', 'м': 'm', 'н': 'n', 'ң': 'n', 'о': 'o', 'ө': 'o',
    'п': 'p', 'р': 'r', 'с': 's', 'т': 't', 'у': 'u', 'ұ': 'u', 'ү': 'u',
    'ф': 'f', 'х': 'h', 'һ': 'h', 'ц': 'ts', 'ч': 'ch', 'ш': 'sh',
    'щ': 'sch', 'ъ': '', 'ы': 'y', 'і': 'i', 'ь': '', 'э': 'e', 'ю': 'iu',
    'я': 'ia',
}


def slugify_kz(text: str, *, max_length: int = 60, fallback: str = 'item') -> str:
    """Текст (казахская кириллица и/или латиница) -> ASCII slug.

    `max_length` короче лимита поля намеренно: вызывающая сторона обычно
    добавляет суффикс уникальности (`-2`, `-3`, …), и без запаса длинный
    заголовок срезался бы уже вместе с ним.
    """
    lowered = (text or '').lower()
    transliterated = ''.join(_CYRILLIC_TO_LATIN.get(ch, ch) for ch in lowered)
    slug = re.sub(r'[^a-z0-9]+', '-', transliterated).strip('-')
    return slug[:max_length].rstrip('-') or fallback
