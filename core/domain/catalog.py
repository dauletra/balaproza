"""Оси каталога: чем читатель сужает выдачу и как это называется.

Ключи — контракт URL (`?kind=`, `?audience=`), подписи — контракт языка
(docs/16). Ни то, ни другое не является данными: набор осей не меняется
от того, сколько в базе произведений, и переживёт замену хранилища.

`KIND_PREDICATES` типизирован по утиному — предикату нужен объект с
`format` и `status`. На Ф14 те же лямбды переводятся в `Q`-выражения, а
ключи и подписи остаются на месте.
"""

