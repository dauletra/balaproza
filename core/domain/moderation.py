"""Модерация как работа человека: очередь, срок ожидания, сравнение версий.

Раздел появился вместо действий в списке админки. Админка умела
принять решение, но не умела показать то, по чему решение принимается:
текст лежал в инлайне глав номерами, повторная подача была неотличима от
первой, а двое модераторов, открывшие одну работу, узнавали друг о друге
только по результату.

Модели здесь нет — только правила: что такое «долго ждёт», чем первая
подача отличается от повторной и как показать разницу между версиями.
"""

from difflib import SequenceMatcher

# Сколько дней ожидания делают заявку «долгой». Три, а не семь: на детской
# платформе автор — подросток, для которого неделя молчания означает, что
# про него забыли.
QUEUE_SLOW_DAYS = 3

# Что платформа обещает автору вслух (D1). Модерация ежедневная, один-два
# человека, — значит сутки, и это обещание стоит на экране отправки.
#
# Обещание важнее точности. Для человека, впервые отдавшего свой текст
# чужим людям на суд, «не знаю, когда» — главный источник тревоги: час
# ожидания и месяц ожидания ощущаются одинаково, пока не названы. Число
# здесь, а не в шаблоне, потому что его же читает раздел модерации,
# отмечая просрочку.
REVIEW_PROMISE_HOURS = 24


def overdue_label(hours: int = REVIEW_PROMISE_HOURS) -> str:
    """Подпись счётчика просрочки — со сроком внутри.

    Здесь, а не в шаблоне: срок один на портал, и подпись, собранная
    рядом с разметкой, стала бы вторым местом, где он записан. Тот же
    приём, что у условий конкурса, — подпись живёт там же, где правило.
    """
    return f'Мерзімнен асқан ({hours} сағат)'


# Оси очереди. Отвечают на разные вопросы модератора: «с чего
# начать сегодня» — это `waiting`, «кого мы держим дольше всех»; `repeat` —
# работа, которую уже возвращали, и её читают, сверяя с замечанием.
QUEUE_FILTERS = (
    ("",        "Барлығы"),
    ("waiting", "Ұзақ күтуде"),
    ("repeat",  "Қайта жіберілген"),
    ("first",   "Алғаш рет"),
    ("mine",    "Мен алғандар"),
)

QUEUE_FILTER_KEYS = tuple(key for key, _label in QUEUE_FILTERS)


def _paragraphs(text: str) -> list:
    """Абзацы текста. Единица сравнения — абзац, а не строка и не слово:
    проза правится абзацами, посимвольный diff по казахскому тексту
    нечитаем, а построчный распадается на обрывки предложений."""
    return [p.strip() for p in (text or '').split('\n') if p.strip()]


def paragraph_diff(old: str, new: str) -> list:
    """Чем новая версия отличается от прежней — списком абзацев.

    Отдаёт `{'kind': 'same'|'added'|'removed', 'text': ...}`. Модератору,
    читающему повторную подачу, важно не перечитать роман заново, а
    увидеть, что изменилось после его же замечания.

    `replace` разворачивается в «убрано» плюс «добавлено»: переписанный
    абзац — это и то, и другое, а показывать их парой значит навязывать
    порядок чтения, которого в тексте нет.
    """
    old_p, new_p = _paragraphs(old), _paragraphs(new)
    matcher = SequenceMatcher(a=old_p, b=new_p, autojunk=False)

    out = []
    for tag, i1, i2, j1, j2 in matcher.get_opcodes():
        if tag in ('delete', 'replace'):
            out += [{'kind': 'removed', 'text': p} for p in old_p[i1:i2]]
        if tag in ('insert', 'replace'):
            out += [{'kind': 'added', 'text': p} for p in new_p[j1:j2]]
        if tag == 'equal':
            out += [{'kind': 'same', 'text': p} for p in old_p[i1:i2]]
    return out


def diff_summary(diff) -> dict:
    """Две цифры над сравнением: сколько абзацев прибыло и сколько ушло.
    Без них модератор не знает, стоит ли вообще разворачивать сравнение."""
    return {
        'added':   sum(1 for row in diff if row['kind'] == 'added'),
        'removed': sum(1 for row in diff if row['kind'] == 'removed'),
    }


