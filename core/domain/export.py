"""Выгрузка своих текстов одним файлом.

Зачем это есть. Провайдер личности один и запасного нет: потерял доступ к
Telegram — потерял всё, что писал, и доказать, что аккаунт твой, нечем.
Для площадки, куда подросток заливает результат полугода работы, этого
достаточно, чтобы кнопка «забрать своё» была обязательной, независимо от
того, случится ли беда.

**Один файл, а не архив.** Архив на телефоне открывается не везде и не
одним касанием, а цель тут — «я нажал и получил свои тексты», причём в
худший день, когда что-то уже пошло не так. Markdown читается любым
текстовым редактором как обычный текст и вставляется в документ целиком.

**Рабочие копии, а не опубликованное.** Автор забирает то, что написал,
включая непоказанное и неодобренное; глава, которой читатель не видит,
для него существует ровно так же, как остальные, — и пометка рядом
говорит только о видимости, а не о том, что текст неполноценный.

Чистые функции: принимают готовую структуру, моделей не знают. Форму
данных собирает `queries/author.export_portfolio` — так документ можно
собрать и проверить без базы.
"""

# Разделитель между произведениями. Горизонтальная черта Markdown —
# единственное, что одинаково читается и как разметка, и как простой
# текст.
_RULE = '\n\n---\n\n'

# Пометка у главы, которой читатель ещё не видит. Не название статуса:
# словарь статусов работы живёт в `status_badge.html` и вторым
# экземпляром здесь разошёлся бы с ним. Это факт о видимости, а не
# мәртебе.
_UNSEEN = ' (оқырманға көрінбейді)'


def _chapter_block(chapter: dict) -> str:
    """Одна глава: заголовок с номером и тело как есть.

    Тело не трогается вовсе — ни отступов, ни переносов: это текст
    автора, и «улучшать» его при выгрузке нельзя.
    """
    mark = '' if chapter['published'] else _UNSEEN
    title = chapter['title'].strip() or f"{chapter['number']}-бөлім"
    head = f"## {chapter['number']}. {title}{mark}"
    body = chapter['body'].strip()
    return f'{head}\n\n{body}' if body else head


def _work_block(work: dict) -> str:
    parts = [f"# {work['title']}"]
    annotation = (work['annotation'] or '').strip()
    if annotation:
        parts.append(annotation)
    if work['chapters']:
        parts.extend(_chapter_block(c) for c in work['chapters'])
    else:
        # Пустая работа тоже едет: у автора она есть, и молча пропасть из
        # выгрузки не должна — иначе он пересчитает свои вещи и не
        # досчитается.
        parts.append('_Мәтін әлі жазылмаған._')
    return '\n\n'.join(parts)


def portfolio_markdown(*, author: str, username: str, exported_on,
                       works: list) -> str:
    """Весь портфель одним документом.

    `exported_on` — дата, и в заголовке она ISO: файл живёт вне портала,
    сортируется в папке загрузок рядом с прошлыми выгрузками, и «5 жел»
    там не отвечает даже на вопрос «какого года».
    """
    header = (f'# {author}\n\n'
              f'@{username} · {exported_on:%Y-%m-%d} · {len(works)} шығарма\n\n'
              f'Бұл — Qazaqnovel-дегі жазғаныңның толық көшірмесі: жарияланғаны '
              f'да, әлі көрсетілмегені де. Файл сенікі, онымен не істесең де '
              f'өз еркің.')
    if not works:
        return f'{header}\n\n_Әзірге жазылған шығарма жоқ._\n'
    blocks = _RULE.join(_work_block(w) for w in works)
    return f'{header}{_RULE}{blocks}\n'


def portfolio_filename(username: str, exported_on) -> str:
    """Имя файла в папке загрузок. Ник и дата: вторая выгрузка через
    месяц не должна затирать первую."""
    return f'qazaqnovel-{username}-{exported_on:%Y-%m-%d}.md'
