"""Произведение: закрытый словарь реакций и путь к публикации.

Реакций пять (DEC-32): открытый список означал бы бесконечную модерацию и
длинный хвост мёртвых кнопок. Порядок чек-листа — порядок работы автора,
а не порядок полей формы (FR-WRITE-09).
"""

from dataclasses import dataclass

# Статусы произведения (BR-10/11, BR-80). Шестой — `NeedsWork` — заведён
# новым DEC: пока модерация выдавалась работе один раз, «доработай» было
# исходом события и ничем в самой работе; с пересчитываемым статусом
# (BR-79) это её настоящее состояние, и автор обязан отличать возвращённое
# от нетронутого черновика в списке из восьми работ.
#
# Подписи здесь не лежат намеренно: их знает `components/status_badge.html`,
# один на весь проект (BR-10), и второй словарь разошёлся бы с ним.
STORY_STATUSES = ("Published", "NotPublished", "NeedsWork", "OnProcess",
                  "Completed", "OnModeration")

# Сколько черновиков без единой публикации автор держит одновременно
# (BR-88). Число не о таланте, а о гигиене: ничем не ограниченное создание
# заводило горы пустых работ (25 POST подряд — 25 работ) без выгоды никому.
# Считаются только `NotPublished` — работа, хоть раз дошедшая до очереди
# или до читателя, в счёт не идёт.
MAX_DRAFT_STORIES = 15

# Потолок объёма одной главы. Не про меру таланта: до него единственным
# пределом была настройка Django на размер тела запроса, и текст, в него
# не влезший, отвергался с невнятной ошибкой уровня фреймворка вместо
# слов. Миллион знаков — восемнадцать часов чтения; у одночастного
# произведения это весь роман целиком, и упереться в этот предел
# по-честному нельзя.
CHAPTER_BODY_MAX = 1_000_000

# Потолок комментария. Поля с пределом у него не было вовсе: `TextField`
# в модели, `CharField` без `max_length` в форме — и один комментарий на
# пять мегабайт ломал страницу произведения для всех, кто её откроет.
# Две тысячи — вчетверо длиннее самого длинного в демо-корпусе.
COMMENT_MAX = 2_000

# Формат выбирает автор и только автор (DEC-28): из числа глав он не
# выводится — у одночастевого произведения глава ровно одна, но и у сериала
# на старте она одна же.
STORY_FORMATS = ("single", "serial")

# Окно оси «Қазір танымал» (DEC-36) — и одновременно глубина журнала
# просмотров: строки старше окна ни на что не влияют и вычищаются
# пересчётом (DEC-55). Число живёт здесь, а не в модели: его спрашивают и
# запрос, и команда пересчёта, и сид.
RECENT_VIEWS_DAYS = 14


# Состояния ревизии главы (BR-79). Единица публикации — глава, а точнее
# её ревизия: одобряется конкретный текст, а не работа целиком.
#
#   draft     — рабочая копия автора, читателю не видна;
#   pending   — отправлена на модерацию, читателю всё ещё не видна;
#   approved  — одобрена; именно она стоит в `Chapter.published_revision`;
#   rejected  — отклонена; прежняя опубликованная остаётся на месте.
REVISION_STATES = ("draft", "pending", "approved", "rejected")


def story_status(*, has_published: bool, has_pending: bool,
                 is_single: bool, completed: bool,
                 returned: bool = False) -> str:
    """Статус работы — **состояние её глав**, а не отдельное решение (BR-79).

    Раньше статус назначался: одобрение ставило `Published`/`OnProcess`, а
    любой отрицательный исход — `NotPublished`. Пока модерация выдавалась
    работе один раз, это сходилось. С модерацией по главам — нет: у
    публичного сериала, чью новую главу вернули на доработку, назначенный
    `NotPublished` увёл бы из каталога уже опубликованные главы, которых
    решение не касалось.

    Отсюда правило: публичность даёт **хотя бы одна опубликованная глава**,
    и ничто другое. `Completed` — слово автора о законченности, а не исход
    модерации; `Published` у сериала невалиден (BR-10a, DEC-37), поэтому
    формат спрашивается здесь, а не подставляется литералом.

    Колонка `Story.status` при этом остаётся — по ней идут `WHERE`,
    `ORDER BY` и четыре индекса каталога, то есть это ровно тот случай,
    который проект допускает (как `Story.likes`). Меняется не то, где она
    лежит, а то, откуда берётся: пересчитывается по строкам, а не ставится.
    """
    if not has_published:
        if has_pending:
            return "OnModeration"
        # `NeedsWork` — только у непубличного (BR-80). У публичной работы,
        # чью новую главу вернули, статус остаётся публичным: увести её из
        # каталога значит наказать читателя за то, чего он не видел.
        return "NeedsWork" if returned else "NotPublished"
    if is_single:
        return "Published"
    return "Completed" if completed else "OnProcess"

