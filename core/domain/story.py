CHECKLIST_TEXT_LABELS = {
    True:  ("Мәтін жаз", "Оқырманға көрсететін нәрсе — осы."),
    False: ("Алғашқы бөлімді жаз", "Оқырманға көрсететін нәрсе — осы."),
}


def checklist_label(key: str, *, is_single: bool) -> tuple:
    """Подпись и пояснение пункта чек-листа: `(label, hint)`."""
    if key == "text":
        return CHECKLIST_TEXT_LABELS[bool(is_single)]
    return CHECKLIST_LABELS[key]
