# Подписи пунктов — здесь, а не в шаблоне (BR-81).
#
# Пока они лежали простынёй `{% if item.key == ... %}` в `publish_panel`,
# назвать недостающее могла только панель. Сообщение об отказе поэтому
# перечисляло причины **на память** — «аннотация мен жас белгісі», — и
