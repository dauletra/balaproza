"""Произведение: закрытый словарь реакций и путь к публикации.

Оба списка закрыты намеренно. Реакций пять (DEC-32): открытый список
означал бы бесконечную модерацию и длинный хвост мёртвых кнопок.
Пунктов чек-листа столько же, сколько условий у публикации (FR-WRITE-09),
и порядок в нём — порядок работы автора, а не порядок полей формы.
"""

from dataclasses import dataclass

# Статусы произведения (BR-10/11). Пять, и шестого без нового DEC не будет:
# `NeedsWork` как состояние работы остаётся кандидатом в V2 (docs/16 §16.3) —
# сейчас «доработай» это исход события модерации, а не то, чем работа стала.
# Подписи здесь не лежат намеренно: их знает `components/status_badge.html`,
# один на весь проект (BR-10), и второй словарь разошёлся бы с ним.
STORY_STATUSES = ("Published", "NotPublished", "OnProcess", "Completed",
                  "OnModeration")

# Формат выбирает автор и только автор (DEC-28): из числа глав он не
# выводится — у одночастевого произведения глава ровно одна, но и у сериала
# на старте она одна же.
STORY_FORMATS = ("single", "serial")


def status_after_moderation(outcome: str, story_format: str) -> str:
    """Каким станет статус работы после решения модератора (BR-11).

    Правило здесь, а не в админке, по той же причине, по которой здесь
    лежат сами статусы: это часть модели публикации, а админка — всего
    лишь сегодняшний инструмент модерации (DEC-23). Завтра тем же
    решением будет распоряжаться вью, и второй экземпляр правила
    разошёлся бы с первым.

    Одобрение **не ставит литерал `Published`** — статус зависит от
    формата (BR-10a, DEC-37): у сериала `Published` невалиден, публичный
    сериал носит `OnProcess` или `Completed`. Одобренный сериал
    продолжается; «дописан» — слово автора, а не модератора, и `Completed`
    ставится отдельно.

    Оба отрицательных исхода возвращают работу в черновики: и «толықтыру
    қажет», и отказ означают, что читателю её сейчас не видно. Разница
    между ними живёт в уведомлении (BR-72b), а не в статусе — состояния
    `NeedsWork` у работы нет (V2-кандидат, docs/16 §16.3).
    """
    if outcome == "approved":
        return "Published" if story_format == "single" else "OnProcess"
    return "NotPublished"

# ───────────────────────── Реакции на главу ───────────────────────────────

@dataclass(frozen=True)
class Reaction:
    """Одна реакция читателя на главу (FR-STORY-12, DEC-32).

    Словарь закрытый: пять штук, пользовательских реакций нет. Открытый
    список означал бы бесконечную модерацию и длинный хвост мёртвых кнопок.
    """
    slug: str
    label: str    # первое лицо — читатель говорит о себе, как в docs/16 («сен»)
    icon: str     # symbol в спрайте; эмодзи запрещены, поэтому только SVG
    hint: str     # как это читать автору в разбивке по главам


# Порядок фиксирован и в данных, и в интерфейсе: кнопки не должны прыгать
# местами по мере голосования.
REACTIONS = (
    Reaction("kuldim",    "Күлдім",    "smile",        "күлкілі болды"),
    Reaction("jyladym",   "Жыладым",   "drop",         "қатты әсер етті"),
    Reaction("juregim",   "Жүрегім",   "heart-filled", "романтикалық"),
    Reaction("shabyt",    "Шабыт",     "feather",      "жазуға шабыттандырды"),
    Reaction("tangaldym", "Таңғалдым", "sparkle",      "күтпеген бұрылыс"),
)

REACTIONS_BY_SLUG = {r.slug: r for r in REACTIONS}


