# ── Что слать в Telegram ─────────────────────────────────────────────────
#
# Один выключатель на всё был бы ровно той ловушкой, ради которой эта
# настройка и заводится: у популярного автора отклики идут потоком, а
# решение модератора приходит раз в неделю и важнее всего остального.
# Выключив «уведомления», он потерял бы второе вместе с первым — то же
# самое, что блокировка бота, только изнутри продукта.
#
# Поэтому три семьи, и делятся они по тому, **про кого событие**:
# платформа отвечает мне, люди отвечают мне, авторы пишут дальше. Шум
# живёт целиком во второй; первая редка и обязательна; третья —
# читательская, и выключают её те, кто на портале пишет, а не читает.
#
# Справочник здесь, а не в форме: по нему собирается и форма профиля, и
# условие выборки очереди (`pending_pushes`), и второй его экземпляр
# разошёлся бы с первым молча — человек снял бы галку, а сообщения шли.


@dataclass(frozen=True)
class PushCategory:
    """Семья событий: колонка у `User`, подпись и что в неё входит."""

