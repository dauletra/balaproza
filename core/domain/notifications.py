# ── Фразы событий ────────────────────────────────────────────────────────
#
# В `text` лежит **только событие**: имя предмета приходит из самого
# предмета (BR-72a), иначе переименование работы оставит уведомление
# врать. Поэтому фраз здесь мало — у комментария, отклика и нового
# подписчика предложение целиком собирает `notification_item.html` из
# объектов, и текста им не нужно вовсе.
#
# Здесь, а не в `queries/`: правило записи живёт в домене — то же место,
# где подписи статусов и фраза конкурса.

# Предел `Notification.text`. Совпадает с `max_length` колонки; держится
# здесь, потому что обрезает не модель, а `comment_quote` ниже.
EVENT_TEXT_MAX = 300


def new_chapter_event(chapters: int = 1) -> str:
    """Что случилось, в уведомлении подписчику.

    Число — частью фразы, а не отдельной колонкой: одно решение модератора
    открывает читателю сразу пачку глав (BR-79), и «жаңа бөлім қосылды» на
    трёх сразу занижало бы событие. Суффикса множественного числа после
    числительного в казахском нет — «3 жаңа бөлім», не «бөлімдер».
    """
    if chapters > 1:
        return f'{chapters} жаңа бөлім қосылды.'
    return 'жаңа бөлім қосылды.'


# Решение по заявке (BR-41). «Қаралуда» здесь нет: это не событие, а
