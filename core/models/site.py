"""Портал целиком: ссылки «Авторлар мектебі» и суточный снимок."""

from django.db import models


class SchoolLink(models.Model):
    """Ссылка «Авторлар мектебі». Страницы школы у платформы нет и
    не будет — есть блок ссылок на написанное другими. Таблицей, потому что
    список меняется чаще, чем выходит релиз."""

    # Площадка: по ней компонент берёт иконку и фирменный цвет.
    channel = models.CharField('арна', max_length=32)
    title = models.CharField('атауы', max_length=120)
    subtitle = models.CharField('мазмұны', max_length=120, blank=True)
    url = models.URLField('сілтеме')
    position = models.PositiveSmallIntegerField('реті', default=0)

    class Meta:
        ordering = ('position', 'pk')
        verbose_name = 'мектеп сілтемесі'
        verbose_name_plural = 'мектеп сілтемелері'

    def __str__(self):
        return self.title


class PortalDay(models.Model):
    """Снимок портала за сутки — то, чего завтра уже не посчитать.

    Правило «производное не хранится» этой таблице не противоречит, а
    объясняет её: здесь нет ни одного числа, которое можно было бы
    восстановить задним числом.

    - накопленные счётчики **убывают**. Удаление аккаунта немедленное и
      полное, работа сносится автором, — и «сколько нас было в среду»
      после среды не восстанавливается ничем;
    - решения модератора уходят каскадом вместе с работой, о которой они
      были;
    - оқылым живёт в журнале **две недели** и чистится суточным
      пересчётом. Возвращаемость читателя — главный вопрос выживания
      портала — считается только пока журнал жив, и позже ответа на него
      нет вовсе.

    Поэтому строка с датой, как `AwardGrant` и `ModerationDecision`: акт,
    а не кэш. Пересчитывать её нечем и незачем, а перезапись за тот же
    день безопасна — команда идемпотентна.

    Накопленные числа — **на момент снимка**, то есть на утро следующего
    дня, а не на полночь. Честный пересчёт «на конец суток» упёрся бы в
    `Story.status`: у него нет истории, и каким он был в полночь, таблица
    не знает. За ночь портал меняется мало, и приблизительность здесь
    дешевле выдуманной точности.
    """

    day = models.DateField('күні', unique=True)

    # Воронка автора — те же четыре ступени, что показывает сводка.
    signed_up = models.PositiveIntegerField('кірді', default=0)
    onboarded = models.PositiveIntegerField('анкетаны аяқтады', default=0)
    wrote = models.PositiveIntegerField('жаза бастады', default=0)
    published = models.PositiveIntegerField('жариялады', default=0)

    # Воронка текста.
    drafts = models.PositiveIntegerField('жоба', default=0)
    public = models.PositiveIntegerField('жарияланған', default=0)

    # Модерация — теми же скользящими семью днями, какими её показывает
    # страница: сравнивать со «вчера» число за неделю и число за сутки
    # значит сравнивать разные вопросы.
    decided_week = models.PositiveIntegerField('аптада шешілді', default=0)
    returned_week = models.PositiveIntegerField('аптада қайтарылды', default=0)
    overdue = models.PositiveIntegerField('мерзімнен асқан', default=0)

    # Читатель. Только вошедший: у гостя личности нет, а заводить её ради
    # счётчика значило бы следить за ребёнком ровно там, где политика
    # обещает обратное.
    #
    # `returning_readers` — сколько из читавших **в этот день** читали и
    # накануне. Знаменатель здесь тот же день, а не вчерашний: доля
    # считается на этой же строке, и «сколько из вчерашних вернулось»
    # потребовало бы соседней. Вопрос получается чуть другой, чем
    # классическое удержание, зато отвечает сам на себя: сколько сегодня
    # пришло знакомых, а не новых.
    readers = models.PositiveIntegerField('оқыған', default=0)
    returning_readers = models.PositiveIntegerField('кеше де оқыған', default=0)

    class Meta:
        ordering = ('-day',)
        get_latest_by = 'day'
        verbose_name = 'портал күні'
        verbose_name_plural = 'портал күндері'

    def __str__(self):
        return f'{self.day}: {self.readers} оқырман'

    @property
    def returning_share(self) -> int:
        """Какая доля читавших в этот день читала и накануне, процентами.

        Именно так, а не «сколько из вчерашних вернулось»: знаменатель —
        этот же день, и число читается со строки целиком, без соседней.

        Ноль читателей — ноль процентов, а не деление на ноль: пустой день
        отвечает «никто», и это законный ответ, а не отсутствие ответа.
        """
        if not self.readers:
            return 0
        return round(100 * self.returning_readers / self.readers)
