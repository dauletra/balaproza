"""Общее для команд обслуживания: флаг `--quiet` и отчёт через него.

Подчёркивание в имени — та же договорённость, что у `_corpus.py`: файл
лежит среди команд, но командой не является, и Django его не подхватит.

Шесть команд повторяли один и тот же `add_arguments` слово в слово,
вместе с подсказкой к флагу. Экономия от их сведения невелика — около
тридцати строк, — но дело не в ней: седьмая команда заводится
копированием шестой, и первый же флаг, нужный всем, пришлось бы
добавлять шесть раз, а забыть — в одной.

Отчёт всех команд обслуживания — **по-английски**: это вывод
инструмента, который читают в логе cron, а не строка интерфейса.
"""

from django.core.management.base import BaseCommand


class QuietCommand(BaseCommand):
    """Команда обслуживания: умеет молчать, когда её зовут из теста."""

    def add_arguments(self, parser):
        parser.add_argument(
            '--quiet', action='store_true',
            help='Без отчёта в stdout (для вызова из тестов).',
        )

    def say(self, options, line: str) -> None:
        """Строка отчёта — или тишина, если попросили молчать.

        Метод, а не `if` в каждой команде: проверку флага легко забыть, и
        забытая она превращает прогон суиты в простыню вывода, из которой
        не видно падений.
        """
        if not options['quiet']:
            self.stdout.write(line)
