"""Уборка того, что копится молча.

Две таблицы растут линейно с возрастом портала и не показываются нигде,
где рост было бы видно.

**Уведомления.** Лента показывает неделю, таблица хранила всё с первого
дня, а событий по шесть типов на каждое действие портала. Растёт она
быстрее любой другой, кроме журнала оқылым, — а тот хотя бы чистится.

**Ревизии глав.** Каждая отправка на модерацию заводит полную копию
тела главы, а потолок у главы — миллион знаков; десять возвратов на
доработку это десять копий одного текста. Удалялись они только каскадом
вместе с главой.

Одной командой, а не двумя: у обеих один повод (таблица растёт, смотреть
на неё некому) и одно расписание. Две строки в cron вместо одной — это
два места, где можно забыть.

Идемпотентна, пропуск дня ничего не портит: правило возрастное, и
пропущенное вчера уберётся завтра.

Что **не** трогается ни при каких условиях — опубликованная ревизия (на
неё смотрит глава, и удалить её значит снять текст с публикации) и
поданная, сколько бы она ни ждала модератора. Подробности и размен — в
`core/queries/write.prune_revisions`.
"""

from core import data
from core.queries.notifications import KEEP_DAYS
from core.queries.write import KEEP_REVISION_DAYS

from ._base import QuietCommand


class Command(QuietCommand):
    help = 'Удаляет старые уведомления и старые снимки текста глав.'

    def handle(self, *args, **options):
        notifications = data.prune_notifications()
        revisions = data.prune_revisions()

        self.say(options,
                 f'{notifications} notifications pruned (older than '
                 f'{KEEP_DAYS} days), {revisions} chapter revisions pruned '
                 f'(older than {KEEP_REVISION_DAYS} days)')
