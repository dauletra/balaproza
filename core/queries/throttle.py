"""Ограничение частоты: сколько раз в минуту человек может это сделать.

Вход через Telegram убирает ботов — и не убирает подростка, решившего
пошалить. До этого предела не было нигде: ни на комментариях, ни на
жалобах, ни на подписках. Сотня комментариев за минуту ничего не ломает
технически и ломает страницу произведения для всех, кто её откроет.

**Считается по самой таблице, а не по кэшу.** Кэш в проекте `locmem`, то
есть свой у каждого рабочего процесса: на четырёх воркерах предел
умножился бы на четыре, причём незаметно. У всех четырёх действий есть
`created_at`, и `COUNT` по своему же индексу стоит меньше, чем ошибка в
пределе. Когда появится общий кэш (Redis), это место можно переписать —
но не раньше, чем он появится.

Предел — **против потока, а не против человека**. Числа выбраны так,
чтобы живой читатель в них не упёрся никогда: десять комментариев в
минуту это один раз в шесть секунд, дольше, чем их печатают.
"""

from datetime import timedelta

from django.core.cache import cache
from django.utils import timezone

from ..models import ChapterReactionVote, Follow, Report, StoryComment

# Окно у всех одно — минута. Разные окна пришлось бы объяснять в каждом
# сообщении об отказе, а объяснять тут нечего: «слишком часто».
WINDOW = timedelta(minutes=1)

# (модель, поле «кто», сколько можно за окно).
LIMITS = {
    'comment':  (StoryComment, 'author', 10),
    'report':   (Report, 'reporter', 5),
    'follow':   (Follow, 'follower', 20),
    'reaction': (ChapterReactionVote, 'user', 30),
}


def too_often(action: str, user) -> bool:
    """Исчерпан ли предел. Гость сюда не доходит — все четыре действия
    требуют входа, — но `None` отвечает «нет», как и везде в слое данных.

    Отдаёт булево, а не бросает: вызывающая сторона отвечает отказом в
    своём стиле — тостом, тихим no-op или кодом ответа.
    """
    if user is None:
        return False
    model, field, limit = LIMITS[action]
    since = timezone.now() - WINDOW
    return model.objects.filter(
        **{field: user, 'created_at__gte': since}).count() >= limit


# ── Действие без своей строки ────────────────────────────────────────────
#
# Выгрузка текстов не оставляет в базе ничего, и считать по таблице её
# нечем. Здесь кэш — единственный доступный счётчик, и его локальность
# (свой у каждого процесса) на этот раз приемлема: предел у выгрузки не
# «десять в минуту», а «одна в минуту», и умноженная на число воркеров
# она остаётся единицами. Разница с комментариями принципиальная —
# там умножение предела меняло бы поведение, видимое читателю.
#
# Само действие дорогое по-другому: портфель собирается целиком в память
# и отдаётся одним файлом. Дважды подряд его не просят, а вот скрипт,
# дёргающий адрес в цикле, повторял бы сборку романов на каждом проходе.

EXPORT_WINDOW_SECONDS = 60


def export_too_often(user) -> bool:
    """Просил ли этот человек свои тексты только что.

    Ставит отметку сам: спрашивают её ровно там, где собираются
    выгружать, и отдельный «отметить» второй дверью только добавил бы
    место, где его можно забыть.
    """
    if user is None:
        return False
    key = f'export:{user.pk}'
    # `add` возвращает False, если ключ уже есть, — атомарно у любого
    # бэкенда, в отличие от пары `get`/`set`.
    return not cache.add(key, True, EXPORT_WINDOW_SECONDS)
