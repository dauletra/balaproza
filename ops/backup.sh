#!/usr/bin/env bash
#
# Бэкап базы и media/. Раз в сутки, из cron.
#
# Содержимое — единственный актив платформы, и до этого скрипта оно
# существовало в одном экземпляре. Рядом живёт удаление аккаунта:
# немедленное, полное, каскадом, без периода хранения. Одна ошибка в коде
# или один неверный клик — и работы автора уходят вместе с чужими
# комментариями на них, безвозвратно.
#
# Два источника, и оба обязательны. База без media/ откроет каталог без
# единой обложки; media/ без базы — папка картинок без имён.
#
# Переменные:
#   DATABASE_URL  строка подключения (та же, что у сайта)
#   MEDIA_DIR     каталог media/ (по умолчанию ../media от этого скрипта)
#   BACKUP_DIR    куда складывать (обязательна)
#
# BACKUP_DIR обязан жить **не на том диске**, где база. Бэкап рядом с
# оригиналом спасает от кривой миграции и не спасает от умершего диска,
# а умирают чаще диски.

set -euo pipefail

: "${DATABASE_URL:?нужна переменная DATABASE_URL}"
: "${BACKUP_DIR:?нужна переменная BACKUP_DIR — каталог на отдельном носителе}"

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MEDIA_DIR="${MEDIA_DIR:-$here/../media}"

today="$(date +%F)"
dest="$BACKUP_DIR/daily/$today"
mkdir -p "$dest"

# ── База ─────────────────────────────────────────────────────────────────
# `--format=custom`: сжат, восстанавливается выборочно и переживает смену
# версии Postgres лучше простого текста.
pg_dump --format=custom --no-owner --no-privileges \
        --file="$dest/db.dump" "$DATABASE_URL"

# ── media/ ───────────────────────────────────────────────────────────────
# Архивом, а не rsync: снимок должен соответствовать дампу базы, а не
# «текущему состоянию папки». Пустой каталог — тоже законный снимок:
# на новом портале обложек ещё нет.
if [ -d "$MEDIA_DIR" ]; then
    tar --create --gzip --file="$dest/media.tar.gz" -C "$MEDIA_DIR" .
else
    echo "media/ не найдена ($MEDIA_DIR) — сохранена только база" >&2
fi

# Что внутри и когда снято — рядом со снимком, а не в имени файла:
# имя копируют, а файл едет вместе с ним.
{
    echo "снято:   $(date --iso-8601=seconds)"
    echo "база:    $(basename "$dest/db.dump") ($(du -h "$dest/db.dump" | cut -f1))"
    [ -f "$dest/media.tar.gz" ] &&
        echo "media:   media.tar.gz ($(du -h "$dest/media.tar.gz" | cut -f1))"
    echo "хост:    $(hostname)"
} > "$dest/manifest.txt"

# ── Ротация ──────────────────────────────────────────────────────────────
# Семь суточных, четыре недельных, шесть месячных. Недельный и месячный —
# жёсткие ссылки на суточный: место занимает один файл, а живёт он
# столько, сколько нужно самой долгой полке.
link_into () {
    local shelf="$1" keep="$2"
    mkdir -p "$BACKUP_DIR/$shelf"
    cp --archive --link "$dest" "$BACKUP_DIR/$shelf/$today" 2>/dev/null || true
    # Лишнее — по дате в имени: полка отсортирована сама собой.
    ls -1 "$BACKUP_DIR/$shelf" | sort | head -n "-$keep" | while read -r old; do
        rm -rf "${BACKUP_DIR:?}/$shelf/$old"
    done
}

link_into daily 7
[ "$(date +%u)" = "7" ] && link_into weekly 4
[ "$(date +%d)" = "01" ] && link_into monthly 6

echo "готово: $dest"
